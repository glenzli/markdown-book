export function normalizeLanguage(value) {
  if (typeof value !== "string") return undefined;
  if (/^zh(?:[-_]|$)/i.test(value)) return "zh-CN";
  if (/^en(?:[-_]|$)/i.test(value)) return "en";
}
export function translate(language, key, values = {}) {
  const message = messages[key]?.[normalizeLanguage(language) ?? "en"];
  if (message === undefined) throw new Error(`Unknown UI message: ${key}`);
  return message.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}
export function translateDom(preferences, root = document) {
  for (const node of root.querySelectorAll(
    "[data-mb-label], [data-mb-label-title], [data-mb-label-aria-label], [data-mb-label-placeholder]",
  )) {
    if (node.closest(".prose") && !node.closest(".book-intro")) continue;
    const values = JSON.parse(node.dataset.mbValues ?? "{}");
    if (node.dataset.mbLabel)
      node.textContent = preferences.t(node.dataset.mbLabel, values);
    for (const attribute of ["title", "aria-label", "placeholder"]) {
      const key = node.getAttribute(`data-mb-label-${attribute}`);
      if (key) node.setAttribute(attribute, preferences.t(key, values));
    }
  }
}
